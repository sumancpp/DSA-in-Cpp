#include<iostream>
using namespace std;
int main (){

// Data type tells the compiler what type of data is stored

// Integer (int) - Stores whole numbers.

int age = 20;
int marks = 95;
cout<<age<<" "<<marks;
cout<<"\n";



// Float - Stores decimal numbers.

float pi = 3.14;
cout<<pi;
cout<<"\n";



// Double - More accurate decimal values.

double value = 3.1415926535;
cout<<value;
cout<<"\n";



// Character - Stores a single character.
char grade = 'A';
char ch = 'x';
cout<<grade<<"  "<<ch;
cout<<"\n";



// Boolean - Stores only
// true
// false

bool pass = false;
cout<<pass;
cout<<"\n";



// String - Stores multiple characters.

string name = "Suman";
cout<<name;

    return 0;
}